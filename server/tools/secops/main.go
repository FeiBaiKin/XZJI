// secops 从 OpenAPI 契约中找出声明了 security 的接口，生成需要登录的接口表。
// oapi-codegen 的 Gin 模板不处理 security，由这里补上，保证契约是唯一依据。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type operation struct {
	OperationID string                 `yaml:"operationId"`
	Security    *[]map[string][]string `yaml:"security"`
}

type spec struct {
	Security []map[string][]string           `yaml:"security"`
	Paths    map[string]map[string]yaml.Node `yaml:"paths"`
}

var methods = map[string]bool{"get": true, "post": true, "put": true, "patch": true, "delete": true, "head": true, "options": true}

func main() {
	specPath := flag.String("spec", "", "OpenAPI 契约文件")
	pkg := flag.String("pkg", "", "生成代码的包名")
	out := flag.String("out", "", "输出文件")
	flag.Parse()
	if *specPath == "" || *pkg == "" || *out == "" {
		log.Fatal("用法：secops -spec api.yaml -pkg public -out security.gen.go")
	}

	raw, err := os.ReadFile(*specPath)
	if err != nil {
		log.Fatal(err)
	}
	var s spec
	if err := yaml.Unmarshal(raw, &s); err != nil {
		log.Fatal(err)
	}

	var secured []string
	for _, item := range s.Paths {
		for method, node := range item {
			if !methods[method] {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				log.Fatal(err)
			}
			// 接口自己的 security 优先；为空数组表示显式取消全局要求
			effective := s.Security
			if op.Security != nil {
				effective = *op.Security
			}
			if len(effective) > 0 && op.OperationID != "" {
				secured = append(secured, strings.ToUpper(op.OperationID[:1])+op.OperationID[1:])
			}
		}
	}
	sort.Strings(secured)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/secops. DO NOT EDIT.\n\npackage %s\n\n", *pkg)
	b.WriteString("// SecuredOperations 契约中声明了 security、需要登录才能调用的接口。\n")
	b.WriteString("var SecuredOperations = map[string]bool{\n")
	for _, id := range secured {
		fmt.Fprintf(&b, "\t%q: true,\n", id)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
